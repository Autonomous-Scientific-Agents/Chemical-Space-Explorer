"""Precompute counts for the web explorer (docs/index.html) and write docs/data.js.

The page lets you pick C plus any of N, O, S, F, Cl, Br, I. All halogens obey
identical rules, so a count depends only on the non-halogen subset and on how
many halogens are present: 8 subsets x 5 halogen counts = 40 runs.

    python scripts/build_site_data.py --max-atoms 12 --samples 8 --jobs 10

Each run is cached in build/site/<key>.json, so an interrupted build resumes.
"""
import argparse
import json
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from chemuniverse import RuleConfig, estimate  # noqa: E402
HALOGENS = ["F", "Cl", "Br", "I"]


def runs():
    for k in range(4):
        for extra in combinations(["N", "O", "S"], k):
            for h in range(5):
                yield "".join(("C",) + extra) + f"_h{h}", ["C", *extra, *HALOGENS[:h]]


def run(key, elements, max_atoms, k_exact, samples, seed):
    t0 = time.time()
    res = estimate(max_atoms, elements, RuleConfig(), k_exact, samples, seed)
    rows = [[r.n, r.count, r.se, r.exact] for r in res]
    return key, {"elements": elements, "rows": rows, "seconds": round(time.time() - t0, 1)}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--max-atoms", type=int, default=12)
    p.add_argument("--exact-up-to", type=int, default=6)
    p.add_argument("--samples", type=int, default=8)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--jobs", type=int, default=None)
    a = p.parse_args()
    cache = ROOT / "build" / "site"
    cache.mkdir(parents=True, exist_ok=True)
    params = {"max_atoms": a.max_atoms, "k_exact": a.exact_up_to, "samples": a.samples, "seed": a.seed}

    results = {}
    todo = []
    for key, elements in runs():
        f = cache / f"{key}.json"
        if f.exists():
            data = json.loads(f.read_text())
            if data.get("params") == params:
                results[key] = data
                continue
        todo.append((key, elements))
    # biggest element sets first so the slowest runs start early
    todo.sort(key=lambda kv: -len(kv[1]))
    print(f"{len(results)} cached, {len(todo)} to run", flush=True)
    with ProcessPoolExecutor(a.jobs) as pool:
        futs = [pool.submit(run, key, el, a.max_atoms, a.exact_up_to, a.samples, a.seed) for key, el in todo]
        for fut in as_completed(futs):
            key, data = fut.result()
            data["params"] = params
            (cache / f"{key}.json").write_text(json.dumps(data))
            results[key] = data
            total = sum(r[1] for r in data["rows"])
            print(f"done {key:10s} {data['seconds']:7.1f}s  total {total:.3g}  ({len(results)}/40)", flush=True)

    out = {
        "generated": time.strftime("%Y-%m-%d"),
        "params": params,
        "rules": "default RuleConfig: valence, bond-order limits, GDB-style strain, heteroatom filters",
        "sets": {k: {"elements": v["elements"], "rows": v["rows"]} for k, v in sorted(results.items())},
    }
    js = "// Generated by scripts/build_site_data.py; do not edit.\nwindow.CHEMUNIVERSE_DATA = " + json.dumps(out) + ";\n"
    (ROOT / "docs" / "data.js").write_text(js)
    print("wrote docs/data.js")


if __name__ == "__main__":
    main()
